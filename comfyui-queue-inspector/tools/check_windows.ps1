function Say($tag, $msg) {
    $color = @{ 'OK' = 'Green'; 'FAIL' = 'Red'; 'WARN' = 'Yellow'; 'INFO' = 'Gray'; 'OLD' = 'Yellow' }[$tag]
    Write-Host ("  [{0,-4}] {1}" -f $tag, $msg) -ForegroundColor $color
}

