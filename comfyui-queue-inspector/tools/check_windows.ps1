# ------------------------------------------------------------------ 1. files
Write-Host "1. Files"
$nOk = 0
foreach ($m in $manifest) {
    $path = Join-Path $root ($m.p -replace '/', '\')
    if (-not (Test-Path -LiteralPath $path)) {
        if ($m.req) { Say 'FAIL' "missing (needed to run): $($m.p)"; $fails++ }
        else { Say 'INFO' "missing (optional, $($m.why)): $($m.p)" }
        continue
    }
    $h = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash
    if ($m.cur -contains $h) { $nOk++ }
    elseif ($m.old -contains $h) { Say 'OLD' "older version, replace with the new file: $($m.p)"; $warns++ }
    else {
        $tag = 'WARN'; if ($m.req) { $tag = 'FAIL'; $fails++ } else { $warns++ }
        Say $tag "content differs from the release (edited or damaged?): $($m.p)"
    }
}
Say 'OK' "$nOk of $($manifest.Count) files identical to the release"
if ($root -match '\\custom_nodes\\') {
    Say 'WARN' "this folder is inside custom_nodes; it is a standalone program, move it out"
    $warns++
}

# ------------------------------------------------------------------ 2. python
Write-Host ""
Write-Host "2. Python (same search order as start_inspector.bat)"
$pyExe = $null
$pyArgs = @()
$candidates = @(
    (Join-Path $root '..\python_embeded\python.exe'),
    (Join-Path $root '..\..\python_embeded\python.exe'),
    (Join-Path $root '..\.venv\Scripts\python.exe'),
    (Join-Path $root '..\venv\Scripts\python.exe')
)
foreach ($c in $candidates) {
    if (Test-Path -LiteralPath $c) { $pyExe = (Resolve-Path -LiteralPath $c).Path; break }
}
if (-not $pyExe -and (Get-Command py -ErrorAction SilentlyContinue)) {
    $pyExe = 'py'; $pyArgs = @('-3')
}
if (-not $pyExe) {
    $real = Get-Command python -All -ErrorAction SilentlyContinue |
        Where-Object { $_.Source -notmatch 'WindowsApps' } | Select-Object -First 1
    if ($real) { $pyExe = $real.Source }
}
if (-not $pyExe) {
    Say 'FAIL' "no Python found. Install Python 3.9+ or set PYEXE in start_inspector.bat"
    $fails++
} else {
    $ver = & $pyExe @pyArgs -c "import sys; print('%d.%d.%d' % sys.version_info[:3])" 2>&1
    $okVer = & $pyExe @pyArgs -c "import sys; print(sys.version_info >= (3, 9))" 2>&1
    $pyShown = ("$pyExe " + ($pyArgs -join ' ')).Trim()
    if ("$okVer" -eq 'True') { Say 'OK' "$pyShown -> Python $ver" }
    else { Say 'FAIL' "$pyExe -> Python $ver (3.9 or newer needed)"; $fails++ }
}

# ------------------------------------------------------------------ 3. comfyui
Write-Host ""
Write-Host "3. ComfyUI (auto-detect order: 8188, then 8000)"
$found = $false
foreach ($port in 8188, 8000) {
    try {
        $info = Invoke-RestMethod -Uri "http://127.0.0.1:$port/prompt" -TimeoutSec 2 -UseBasicParsing
        $q = Invoke-RestMethod -Uri "http://127.0.0.1:$port/queue" -TimeoutSec 5 -UseBasicParsing
        $nRun = @($q.queue_running).Count
        $nPen = @($q.queue_pending).Count
        Say 'OK' ("ComfyUI answers on 127.0.0.1:{0} (running {1}, pending {2})" -f $port, $nRun, $nPen)
        if (-not $found) { Say 'INFO' "the inspector will connect to port $port" }
        $found = $true
    } catch {
        Say 'INFO' "nothing on 127.0.0.1:$port"
    }
}
if (-not $found) {
    Say 'WARN' "ComfyUI not running (or on another port). Start it, or set COMFY in start_inspector.bat"
    $warns++
}

# ------------------------------------------------------------------ 4. port 8190
Write-Host ""
Write-Host "4. Inspector port 8190"
$listen = $null
if ($onWindows) {
    $listen = Get-NetTCPConnection -LocalPort 8190 -State Listen -ErrorAction SilentlyContinue | Select-Object -First 1
}
if (-not $onWindows) {
    Say 'INFO' "skipped (not Windows)"
} elseif ($listen) {
    $proc = Get-Process -Id $listen.OwningProcess -ErrorAction SilentlyContinue
    Say 'WARN' "port 8190 already in use by $($proc.ProcessName) (PID $($listen.OwningProcess)). If that is not the inspector, run: start_inspector.bat --port 8191"
    $warns++
} else {
    Say 'OK' "port 8190 is free"
}

# ------------------------------------------------------------------ 5. download block
Write-Host ""
Write-Host "5. Downloaded-file block (SmartScreen)"
$blocked = @()
if ($onWindows) {
    $blocked = @(Get-ChildItem -LiteralPath $root -Recurse -File -ErrorAction SilentlyContinue |
        Where-Object { Get-Item -LiteralPath $_.FullName -Stream Zone.Identifier -ErrorAction SilentlyContinue })
}
if (-not $onWindows) {
    Say 'INFO' "skipped (not Windows)"
} elseif ($blocked.Count -gt 0) {
    Say 'INFO' "$($blocked.Count) file(s) carry the 'downloaded from internet' mark."
    Say 'INFO' "Windows may warn when starting start_inspector.bat: choose 'More info' > 'Run anyway'."
    Say 'INFO' "To remove the mark: Get-ChildItem -Recurse '$root' | Unblock-File"
} else {
    Say 'OK' "no files are marked as downloaded"
}

# ------------------------------------------------------------------ 6. unit tests
Write-Host ""
Write-Host "6. Unit tests"
if ($pyExe -and (Test-Path -LiteralPath (Join-Path $root 'tests'))) {
    Push-Location $root
    $out = & $pyExe @pyArgs -B -m unittest discover -s tests 2>&1
    $code = $LASTEXITCODE
    Pop-Location
    $summary = ($out | Where-Object { "$_" -match '^(Ran |OK|FAILED)' }) -join ' / '
    if ($code -eq 0) { Say 'OK' $summary }
    else {
        Say 'FAIL' $summary
        $out | Select-Object -Last 25 | ForEach-Object { Write-Host "         $_" }
        $fails++
    }
} else {
    Say 'INFO' "skipped (no Python or no tests folder)"
}

# ------------------------------------------------------------------ summary
Write-Host ""
if ($fails -eq 0 -and $warns -eq 0) {
    Write-Host "Result: all good. Start with start_inspector.bat" -ForegroundColor Green
} elseif ($fails -eq 0) {
    Write-Host "Result: usable, $warns warning(s) above" -ForegroundColor Yellow
} else {
    Write-Host "Result: $fails problem(s), $warns warning(s) - see [FAIL] lines above" -ForegroundColor Red
}
